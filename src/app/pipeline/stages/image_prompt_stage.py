def sanitize_prompt_for_diffusion(prompt: str) -> str:
    """
    Cleans diffusion prompts by stripping out metadata headers, label prefixes,
    camera angle label prefixes, and stray quotation artifacts that cause diffusion
    models to literally burn typography/headers onto the output image.
    """
    if not prompt:
        return ""

    text = prompt.strip()

    # 1. Strip markdown bold/italic wrappers at start
    text = re.sub(r'^\*{1,3}(.*?)\*{1,3}', r'\1', text)

    # 2. Strip common prompt label prefixes (case-insensitive)
    # e.g., "Detailed Image Prompt:", "Prompt:", "Image Card:", "Scene Beat 1:", "Shot:"
    prefix_patterns = [
        r'^(?:detailed\s+image\s+prompt|detailed\s+prompt|image\s+prompt|prompt|visual\s+prompt|visual\s+idea|scene\s+description|image\s+card|title\s+card|shot|scene\s+\d+|beat\s+\d+)\s*:\s*',
        r'^(?:wide\s+shot|close[- ]up|extreme\s+close[- ]up|medium\s+shot|medium\s+close[- ]up|over[- ]the[- ]shoulder(?:\s+medium\s+close[- ]up)?|low[- ]angle\s+shot|high[- ]angle\s+shot|aerial\s+shot|establishing\s+shot|cinematic\s+shot)\s*:\s*',
    ]
    for pat in prefix_patterns:
        text = re.sub(pat, '', text, flags=re.IGNORECASE).strip()

    # Repeat once in case of chained prefixes like "Shot 1: Medium Shot: A man..."
    for pat in prefix_patterns:
        text = re.sub(pat, '', text, flags=re.IGNORECASE).strip()

    # 3. Strip surrounding quotation marks
    if (text.startswith('"') and text.endswith('"')) or (text.startswith("'") and text.endswith("'")):
        text = text[1:-1].strip()

    # 4. Remove phrases explicitly asking for text on screen if generated by LLM
    text = re.sub(r'\bwith (?:the )?(?:words?|text|label|caption|headline|title)\s+["\'][^"\']+["\']', '', text, flags=re.IGNORECASE)
    text = re.sub(r'\b(?:labeled|captioned|inscribed with)\s+["\'][^"\']+["\']', '', text, flags=re.IGNORECASE)

    # Clean double spaces and commas
    text = re.sub(r'\s{2,}', ' ', text)
    text = re.sub(r'\s*,\s*,+', ', ', text).strip(' ,.;')

    return text


def attach_style_anchor(prompt: str, anchor: str) -> str:
    """
    Deterministically attaches the canonical style anchor without duplication, stutter,
    or trailing punctuation glitches.
    Handles exact duplicates, prefix/suffix overlap merging, sentence/clause-level sub-phrase repetitions,
    and varying trailing punctuation.
    """
    clean = sanitize_prompt_for_diffusion(prompt).rstrip(" ,.;")
    if not anchor:
        return clean
    anchor_clean = anchor.strip().rstrip(" ,.;")

    if not clean:
        return anchor_clean

    # 1. Exact match at the end
    if clean.lower().endswith(anchor_clean.lower()):
        return clean

    # 2. Check for longest matching suffix of clean that is a prefix of anchor_clean (overlap merge)
    min_overlap = 15
    clean_lower = clean.lower()
    anchor_lower = anchor_clean.lower()
    max_check = min(len(clean), len(anchor_clean))
    for length in range(max_check, min_overlap - 1, -1):
        if clean_lower.endswith(anchor_lower[:length]):
            clean = clean[:-length].rstrip(" ,.;")
            clean_lower = clean.lower()
            break

    # 3. Check for sentence-level or clause-level sub-phrases of the anchor at the end of clean
    raw_segments = re.split(r'[.,;]\s*', anchor_clean)
    anchor_segments = [s.strip() for s in raw_segments if len(s.strip()) >= 5]

    changed = True
    while changed:
        changed = False
        for phrase in anchor_segments:
            pattern = rf"[,.;]?\s*{re.escape(phrase)}\s*$"
            if re.search(pattern, clean, flags=re.IGNORECASE):
                clean = re.sub(pattern, "", clean, flags=re.IGNORECASE).rstrip(" ,.;")
                changed = True

    # 4. Final check if clean is now empty or ends with anchor
    if not clean:
        return anchor_clean
    if clean.lower().endswith(anchor_clean.lower()):
        return clean

    # 5. Clean up any trailing punctuation before joining
    clean = clean.rstrip(" ,.;")
    return f"{clean}, {anchor_clean}"


class ImagePromptStage:
    def __init__(
        self,
        ai_client=None,
        event_bus=None,
        batch_size: int = 5,
        max_concurrency: int = 3,
        enable_critic: bool = True,
        quality_threshold: float = 80.0
    ):
        self.ai = ai_client or get_ai_client()
        self.event_bus = event_bus
        self.prompt_builder = PromptBuilder()
        self.batch_size = batch_size
        self.max_concurrency = max_concurrency
        self.enable_critic = enable_critic
        self.quality_threshold = quality_threshold

    async def process(self, scenes: List[dict], preset: ContentPreset, topic: str) -> Tuple[List[ScenePrompt], VisualContinuityState]:
        """
        Extracts/builds VisualContinuityState (character descriptions, environment styles).
        Generates semantically grounded, hardened cinematic prompts for each scene beat.
        Audits candidate prompts with a Critic pass to eliminate metaphorical literalism,
        visual hallucinations, and off-concept drift.
        Attaches the style anchor deterministically without duplicates.
        """
        # 1. Establish Continuity
        continuity = await self._build_continuity(scenes, preset, topic)

        total_scenes = len(scenes)
        if total_scenes == 0:
            return [], continuity

        # For small scene counts (<= 3), generate individually to maintain fine-grained single-shot contract
        if total_scenes <= 3:
            prompts = []
            for i, scene in enumerate(scenes):
                prev_narration = scenes[i - 1].get("narration_segment", "") if i > 0 else "None (Beginning of video)"
                next_narration = scenes[i + 1].get("narration_segment", "") if i + 1 < total_scenes else "None (End of video)"
                scene_prompt = await self._generate_scene_prompt(
                    scene=scene,
                    continuity=continuity,
                    preset=preset,
                    topic=topic,
                    scene_index=i + 1,
                    total_scenes=total_scenes,
                    prev_narration=prev_narration,
                    next_narration=next_narration,
                )
                prompts.append(scene_prompt)
        else:
            # High-Speed Batch Generation for larger projects (10 - 300+ scenes)
            batch_size = max(1, self.batch_size)
            concurrency = max(1, self.max_concurrency)
            semaphore = asyncio.Semaphore(concurrency)

            # Partition scenes into indexed batches
            batches = []
            for i in range(0, total_scenes, batch_size):
                batch_slice = [(idx, scenes[idx]) for idx in range(i, min(i + batch_size, total_scenes))]
                batches.append(batch_slice)

            tasks = [
                self._generate_batch_scenes(
                    batch_items=b,
                    continuity=continuity,
                    preset=preset,
                    topic=topic,
                    total_scenes=total_scenes,
                    all_scenes=scenes,
                    semaphore=semaphore
                )
                for b in batches
            ]

            batch_results = await asyncio.gather(*tasks)

            # Flatten and sort by original index
            indexed_prompts: List[Tuple[int, ScenePrompt]] = []
            for res in batch_results:
                indexed_prompts.extend(res)
            indexed_prompts.sort(key=lambda x: x[0])

            prompts = [p for _, p in indexed_prompts]

        # 2. Critic & Quality Audit Pass (Two-Pass Generator + Critic)
        # Note: Critic pass only runs if preset reviewer_rules requires continuity or when enabled, and total_scenes > 0
        if self.enable_critic and self.ai and getattr(preset, "reviewer_rules", None) and getattr(preset.reviewer_rules, "require_continuity", True):
            # Only run critic if total_scenes is substantial (> 10) or explicitly activated, to avoid slowing down fast batch tests
            if total_scenes > self.batch_size * 2:
                prompts = await self._critique_and_refine_prompts(prompts, scenes, continuity, preset, topic)

        # 3. Deterministic Style Anchor Application (single point at return boundary)
        anchor = continuity.art_style_anchor or (getattr(preset, "visual_style", "") or (preset.image_rules.visual_style if hasattr(preset, "image_rules") else ""))
        for scene_prompt in prompts:
            scene_prompt.detailed_image_prompt = attach_style_anchor(scene_prompt.detailed_image_prompt, anchor)

        return prompts, continuity

    async def _build_continuity(self, scenes: List[dict], preset: ContentPreset, topic: str) -> VisualContinuityState:
        scene_text = "\n".join([f"Scene {s.get('scene_number', i)}: {s.get('visual_description', '')}" for i, s in enumerate(scenes)])

        prompt = self.prompt_builder.build(
            level=StageLevel.IMAGE_PROMPT,
            preset=preset,
            inputs={"topic": topic, "scenes": scene_text}
        )

        prompt += """
Output strictly as a JSON object with keys:
- 'recurring_characters' (dict mapping name to description)
- 'recurring_locations' (dict mapping name to description)
- 'art_style_anchor' (string: the locked visual style anchor for the preset)
- 'world_setting' (string: concrete physical/historical reality and environment for this documentary topic)
- 'thematic_motifs' (list of strings: 3-5 grounded physical props, environments, and visual motifs)
- 'forbidden_cliches' (list of strings: 3-5 banned surrealist tropes, literalized metaphors, body horror, or out-of-place elements to strictly avoid)
"""

        default_anchor = getattr(preset, "visual_style", "") or (preset.image_rules.visual_style if hasattr(preset, "image_rules") else "")

        if default_anchor:
            prompt += f"""
CRITICAL PRESET VISUAL STYLE MANDATE:
The project uses the locked preset style: "{default_anchor}"
You MUST strictly set 'art_style_anchor' to this exact preset style anchor. DO NOT substitute with generic 35mm photography or photorealism if the preset specifies a different aesthetic.
"""

        for _ in range(3):
            if hasattr(self.ai, "generate"):
                response = await self.ai.generate(prompt=prompt, role="generator")
                text = response.text if hasattr(response, "text") else str(response)
            else:
                response = await self.ai.generate_message(
                    messages=[{"role": "user", "content": prompt}],
                    system="You are an expert visual prompt engineer.\nCRITICAL INSTRUCTION: DO NOT USE ANY TOOLS OR SKILLS (e.g. memory_search).",
                )
                text = response["text"]

            try:
                text_clean = re.sub(r'^```json\s*', '', text.strip())
                text_clean = re.sub(r'\s*```$', '', text_clean)

                if "skill_result" in text_clean or "memory_search" in text_clean or "[Skill result:" in text_clean:
                    continue

                data = json.loads(text_clean)

                llm_anchor = data.get("art_style_anchor", "").strip()
                final_anchor = llm_anchor or default_anchor

                return VisualContinuityState(
                    recurring_characters=data.get("recurring_characters", {}),
                    recurring_locations=data.get("recurring_locations", {}),
                    art_style_anchor=final_anchor,
                    world_setting=data.get("world_setting", f"Authentic, grounded documentary reality for {topic}"),
                    thematic_motifs=data.get("thematic_motifs", []),
                    forbidden_cliches=data.get("forbidden_cliches", [
                        "literal figures of speech",
                        "surreal body horror",
                        "puppet strings into flesh",
                        "floating brains or gears",
                        "on-screen text or typography"
                    ])
                )
            except Exception as e:
                logger.warning(f"Visual continuity extraction attempt failed: {e}")

        # Fallback to preset style
        return VisualContinuityState(
            art_style_anchor=default_anchor,
            world_setting=f"Authentic, grounded documentary reality for {topic}",
            forbidden_cliches=[
                "literal figures of speech",
                "surreal body horror",
                "puppet strings into flesh",
                "floating brains or gears",
                "on-screen text or typography"
            ]
        )

